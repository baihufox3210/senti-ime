#!/usr/bin/env python3
"""Build authored, controlled Taiwanese Chinese grammar supplements.

Training-only: these are synthetic grammar examples, not collected conversation
or an independent real-world benchmark. Reported user regression sentences are
explicitly excluded, so they are not memorized as complete training sentences.
"""
from pathlib import Path
import argparse,hashlib,json
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
prefixes=['請先','麻煩你先','我們必須先','你可以先','他準備先','她打算先','使用者應該先','工作人員需要先','記得先','建議先','如果已經','當你','等到你','我們已經','他們已經','昨天我','今天我','工程師剛剛','同學正在','老師已經']
software={
 '閱讀':['文件','報告','文章','說明','使用手冊'],
 '填寫':['表單','內容','資料','申請書'],
 '輸入':['資料','內容','指令','姓名'],
 '處理':['資料','文件','任務','申請'],
 '整理':['資料','文件','內容','報告'],
 '檢查':['程式','設定','內容','作業'],
 '修正':['錯誤','問題','格式'],
 '更新':['程式','軟體','系統','設定'],
 '下載':['檔案','文件','圖片','軟體'],
 '安裝':['程式','軟體','系統','套件'],
 '寫':['報告','信件','程式','作業'],
 '測試':['程式','功能','系統','套件'],
 '編輯':['文件','內容','文章','報告'],
 '複製':['檔案','內容','資料'],
 '傳送':['檔案','文件','報告'],
 '上傳':['檔案','圖片','影片'],
 '儲存':['檔案','文件','設定'],
 '刪除':['檔案','內容','資料'],
}
endings=['再繼續下一個步驟。','再關閉視窗。','再確認結果。','之後請檢查是否有錯誤。','之後就可以繼續工作。','以後再通知負責人。','再回到主畫面。','之後請保留備份。']
rows=set()
for verb,objects in software.items():
 for obj in objects:
  for prefix in prefixes:
   for ending in endings:rows.add(f'{prefix}{verb}完{obj}，{ending}')
for verb,objects in {'吃':['飯','早餐','午餐','晚餐'],'喝':['水','茶','飲料'],'看':['書','電影','新聞'],'收拾':['房間','行李','桌子']}.items():
 for obj in objects:
  for prefix in ['記得先','我們已經','等你','我剛剛','他們已經','請先']:
   for ending in ['再出門。','再休息一下。','之後再回家。','以後請整理乾淨。']:
    rows.add(f'{prefix}{verb}完{obj}，{ending}')
for subject in ['孩子','小朋友','學生','妹妹','弟弟','朋友','他們']:
 for where in ['在公園','在家裡','在學校','放學之後','週末的時候','吃過飯之後']:
  for activity in ['玩遊戲','玩球','玩積木','玩玩具','玩捉迷藏','一起玩耍']:
   rows.add(f'{subject}{where}{activity}。')
for obj in ['工具','書籍','餐廳','景點','課程','方法','網站','應用程式']:
 for subject in ['朋友','老師','同事','同學','專家','工程師']:
  for ending in ['很實用。','適合初學者。','值得參考。','可以先試用看看。']:
   rows.add(f'{subject}推薦的{obj}{ending}')
for domain in ['機器學習','資料分析','軟體測試','影像辨識','語音辨識','自然語言處理','科學研究','醫療研究']:
 for operation in ['清理','檢查','標註','整理','下載','備份','匯入','匯出','更新','儲存']:
  rows.add(f'{domain}需要先{operation}資料，再確認資料品質。')
  rows.add(f'{domain}的訓練資料與驗證資料必須分開處理。')
heldout=['推薦之後','補全完文字','補全玩文字','資料及','介紹一下你自己並且自動選字']
rows=sorted(s for s in rows if not any(term in s for term in heldout))
path=ROOT/'crates/senti-predictors/data/domain_sentences.txt'
content='# Authored controlled grammar supplement; generated by scripts/build_domain_corpus.py. Training only, not independent evaluation.\n'+'\n'.join(rows)+'\n'
if args.check:
    if not path.exists() or path.read_text()!=content:raise SystemExit('Domain corpus is stale; rerun scripts/build_domain_corpus.py')
else:path.write_text(content)
print(json.dumps({'sentences':len(rows),'sha256':hashlib.sha256(content.encode()).hexdigest()}))
